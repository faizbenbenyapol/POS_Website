/**
 * แยกว่ารายการอาหารไปสถานีครัวหรือบาร์ ใช้ทั้งกระดานออเดอร์ ตั๋วพิมพ์ และตัวกรองสถานี
 *
 * เดิมหาคำในชื่อเมนูรวมกับชื่อหมวด เช่น "น้ำ" หรือ "ชา" ที่ไหนก็ได้ในข้อความ
 * "ปีกไก่ทอดน้ำปลา" กับ "ต้มยำกุ้งน้ำข้น" จึงถูกส่งไปบาร์ทั้งที่เป็นอาหาร
 * ตอนนี้ตัดสินจากหมวดหมู่เป็นหลัก เพราะร้านจัดหมวดเองและตรงกว่าการเดาจากชื่อจาน
 * เดาจากชื่อเฉพาะเมื่อไม่รู้หมวด และดูแค่คำขึ้นต้นชื่อ (น้ำมะนาว ชาไทย กาแฟเย็น)
 */

/** ชื่อหมวดที่เป็นงานของบาร์ */
const BAR_CATEGORY = /เครื่องดื่ม|ของหวาน|ขนมหวาน|ไอศกรีม|กาแฟ|เบียร์|ไวน์|ค็อกเทล|drink|beverage|dessert|coffee|tea|bar/i;

/** คำขึ้นต้นชื่อเมนูที่เป็นเครื่องดื่ม ใช้เมื่อไม่รู้หมวด */
const BAR_NAME_PREFIX = /^(น้ำ|ชา|กาแฟ|โกโก้|นมสด|นมเย็น|โซดา|เบียร์|ไวน์|ค็อกเทล|สมูทตี้|ไอศกรีม)/;

/** คำภาษาอังกฤษในชื่อเมนูที่เป็นเครื่องดื่ม ใช้เมื่อไม่รู้หมวด */
const BAR_NAME_WORD = /\b(drink|coffee|tea|latte|beer|wine|soda|juice|smoothie)\b/i;

/** ข้อมูลเท่าที่การแยกสถานีต้องใช้ */
export type RoutableItem = {
  itemName: string;
  categoryName?: string | null;
  /** ไม่ใช้ในการตัดสิน รับไว้เพราะผู้เรียกส่งรายการอาหารทั้งแถวมา */
  quantity?: number;
};

/**
 * ตรวจว่ารายการนี้เป็นงานของบาร์เครื่องดื่มหรือไม่
 *
 * @param item - ชื่อเมนูและชื่อหมวด (ถ้ามี)
 * @returns true เมื่อเป็นงานของบาร์ false เมื่อเป็นงานของครัว
 */
export function isBarItem(item: RoutableItem): boolean {
  const category = item.categoryName?.trim();
  if (category) return BAR_CATEGORY.test(category);
  const name = item.itemName.trim();
  return BAR_NAME_PREFIX.test(name) || BAR_NAME_WORD.test(name);
}
